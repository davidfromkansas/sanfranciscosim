// Unmapped OSM values are reported by lore.mjs; the tables above stay explicit.
export function osmSub(tags) {
  if (!tags) return { sub: null, unmapped: null };
  const { amenity, shop, tourism, building, leisure, railway, office, religion, cuisine } = tags;
  if (amenity === 'place_of_worship') {
    const byReligion = OSM_RELIGION_SUB[religion];
    if (byReligion) return { sub: byReligion, unmapped: null };
    const denom = (tags.denomination || '').toLowerCase();
    if (denom === 'quaker') return { sub: 'meeting_house', unmapped: null };
    if ((tags.building || '') === 'cathedral' || /cathedral/i.test(tags.name || '')) {
      return { sub: 'cathedral', unmapped: null };
    }
    return { sub: 'church', unmapped: null };
  }
  if (amenity === 'restaurant' || amenity === 'fast_food') {
    const c = (cuisine || '').toLowerCase();
    if (/mexican|taco|burrito/.test(c)) return { sub: 'taqueria', unmapped: null };
    if (/pizza/.test(c)) return { sub: 'pizzeria', unmapped: null };
    if (/ice_cream/.test(c)) return { sub: 'ice_cream', unmapped: null };
    if (/coffee|cafe/.test(c)) return { sub: 'cafe', unmapped: null };
    return { sub: 'restaurant', unmapped: null };
  }
  if (amenity === 'bar' || amenity === 'pub') {
    const drink = `${tags['drink:wine'] || ''}${tags.microbrewery || ''}`;
    if (tags.microbrewery === 'yes' || /brew/i.test(tags.name || '')) return { sub: 'brewery', unmapped: null };
    if (/wine/i.test(`${tags.name || ''}${drink}`)) return { sub: 'wine_bar', unmapped: null };
    return { sub: 'bar', unmapped: null };
  }
  if (amenity === 'school') {
    const grades = `${tags['isced:level'] || ''} ${tags.name || ''}`.toLowerCase();
    if (/high school|secondary/.test(grades)) return { sub: 'high_school', unmapped: null };
    if (/middle school|junior high/.test(grades)) return { sub: 'middle_school', unmapped: null };
    return { sub: 'elementary_school', unmapped: null };
  }
  if (railway === 'station' || railway === 'subway_entrance') {
    const name = (tags.name || '').toLowerCase();
    if (tags.station === 'subway' || /bart/.test(name)) return { sub: 'bart_station', unmapped: null };
    return { sub: 'muni_station', unmapped: null };
  }
  if (leisure === 'fitness_centre' || leisure === 'sports_centre') return { sub: 'gym', unmapped: null };
  if (leisure === 'swimming_pool') return { sub: 'pool', unmapped: null };
  if (amenity && amenity in OSM_AMENITY) return { sub: OSM_AMENITY[amenity], unmapped: null };
  if (shop && shop in OSM_SHOP) return { sub: OSM_SHOP[shop], unmapped: null };
  if (tourism && tourism in OSM_TOURISM) return { sub: OSM_TOURISM[tourism], unmapped: null };
  if (office && office in OSM_OFFICE) return { sub: OSM_OFFICE[office], unmapped: null };
  if (building && building in OSM_BUILDING) return { sub: OSM_BUILDING[building], unmapped: null };
  const unmapped =
    (amenity && `amenity=${amenity}`) ||
    (shop && `shop=${shop}`) ||
    (tourism && `tourism=${tourism}`) ||
    (office && `office=${office}`) ||
    (building && `building=${building}`) ||
    null;
  return { sub: null, unmapped };
}

