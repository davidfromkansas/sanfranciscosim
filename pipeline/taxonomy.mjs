export function schoolSub(record) {
  const low = parseInt(record.low_grade, 10);
  const high = parseInt(record.high_grade, 10);
  const type = `${record.entity_type || ''} ${record.educational_program_type || ''}`.toLowerCase();
  if (/preschool|early education|child development/.test(type)) return 'preschool';
  if (Number.isFinite(high) && high >= 9) return 'high_school';
  if (Number.isFinite(low) && low >= 6) return 'middle_school';
  if (Number.isFinite(high) && high >= 6) return 'middle_school';
  return 'elementary_school';
}

// ------------------------------------------------------------------ Land use
// c5ge-t6pj carries per-parcel square footage by use plus a residential flag;
// the dominant non-residential use wins when there are no dwellings.
export function landuseCat(parcel) {
  const n = (v) => {
    const x = parseFloat(v);
    return Number.isFinite(x) ? x : 0;
  };
  const res = n(parcel.resunits);
  const uses = [
    ['retail', n(parcel.retail), 4],
    ['cie', n(parcel.cie), 0],
    ['med', n(parcel.med), 12],
    ['mips', n(parcel.mips), 3],
    ['pdr', n(parcel.pdr), 19],
    ['visitor', n(parcel.visitor), 7],
  ];
  uses.sort((a, b) => b[1] - a[1]);
  const top = uses[0];
  const commercial = top[1] > 0 ? top[2] : null;
  if (parcel.garage === true || parcel.parking_lo === true) return 23;
  if (res >= 1) {
    // SF's corridors are flats over storefronts: a parcel with real commercial
    // floor area reads as its ground-floor use, which is what the street sees.
    if (commercial !== null && top[1] >= 1000) return commercial;
    return res >= 5 ? 2 : 1;
  }
  return commercial;
}

// Night-window profiles per category (§2.5.1): 0 residential, 1 commercial,
// 2 always-on, 3 dark.
export const NIGHT_PROFILE = (() => {
  const p = new Array(CATS.length).fill(3);
  for (const c of ['house', 'apartments', 'hotel']) p[CAT_INDEX.get(c)] = 0;
  for (const c of [
    'retail',
    'restaurant_cafe',
    'bar',
    'theater_cinema',
    'gym',
    'supermarket',
    'gas_station',
    'museum',
    'library',
  ]) {
    p[CAT_INDEX.get(c)] = 1;
  }
  for (const c of ['hospital', 'clinic', 'fire_station', 'police', 'transit_station', 'government']) {
    p[CAT_INDEX.get(c)] = 2;
  }
  return p;
})();

